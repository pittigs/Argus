type TerraformResourceExport struct {
	HCLCode  string `json:"hcl_code"`
	JSONPlan string `json:"json_plan"`
}

func GenerateTerraformHCL(users []string, roles []string, fileShares []string) TerraformResourceExport {
	hcl := `# Generated by ARGUS IAM Terraform Provider Exporter
terraform {
  required_providers {
    argus = {
      source  = "argus-security/argus"
      version = "~> 2.0"
    }
  }
}

provider "argus" {
  endpoint  = "http://localhost:8080"
  api_token = var.argus_token
}

`
	for _, r := range roles {
		hcl += fmt.Sprintf(`resource "argus_role" "%s" {
  name        = "%s"
  description = "Managed via Terraform IaC"
}

`, cleanIdentifier(r), r)
	}

	for _, u := range users {
		hcl += fmt.Sprintf(`resource "argus_user" "%s" {
  username  = "%s"
  email     = "%s@corp.local"
  full_name = "%s"
}

`, cleanIdentifier(u), u, u, u)
	}

	return TerraformResourceExport{
		HCLCode:  hcl,
		JSONPlan: `{"terraform_version": "1.7.0", "format_version": "1.2"}`,
	}
}

func cleanIdentifier(s string) string {
	s = stringsReplace(s, ".", "_")
	s = stringsReplace(s, "-", "_")
	return s
}

func stringsReplace(s, old, newStr string) string {
	res := ""
	for i := 0; i < len(s); i++ {
		if string(s[i]) == old {
			res += newStr
		} else {
			res += string(s[i])
		}
	}
	return res
}

