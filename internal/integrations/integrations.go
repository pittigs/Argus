// 38. SCIM 2.0 Protocol (RFC 7643 / RFC 7644)
// -------------------------------------------------------------

type SCIMName struct {
	Formatted  string `json:"formatted"`
	FamilyName string `json:"familyName"`
	GivenName  string `json:"givenName"`
}

type SCIMEmail struct {
	Value   string `json:"value"`
	Primary bool   `json:"primary"`
}

type SCIMUserResource struct {
	Schemas  []string    `json:"schemas"`
	ID       string      `json:"id"`
	UserName string      `json:"userName"`
	Name     SCIMName    `json:"name"`
	Emails   []SCIMEmail `json:"emails"`
	Active   bool        `json:"active"`
}

type SCIMListResponse struct {
	Schemas      []string `json:"schemas"`
	TotalResults int      `json:"totalResults"`
	StartIndex   int      `json:"startIndex"`
	ItemsPerPage int      `json:"itemsPerPage"`
	Resources    []any    `json:"Resources"`
}

type SCIMServer struct {
	users map[string]SCIMUserResource
	mu    sync.RWMutex
}

func NewSCIMServer() *SCIMServer {
	ss := &SCIMServer{
		users: make(map[string]SCIMUserResource),
	}
	ss.users["user-1"] = SCIMUserResource{
		Schemas:  []string{"urn:ietf:params:scim:schemas:core:2.0:User"},
		ID:       "user-1",
		UserName: "sarah.connor",
		Name:     SCIMName{Formatted: "Sarah Connor", FamilyName: "Connor", GivenName: "Sarah"},
		Emails:   []SCIMEmail{{Value: "s.connor@corp.local", Primary: true}},
		Active:   true,
	}
	return ss
}

func (ss *SCIMServer) ListUsers() SCIMListResponse {
	ss.mu.RLock()
	defer ss.mu.RUnlock()
	var res []any
	for _, u := range ss.users {
		res = append(res, u)
	}
	return SCIMListResponse{
		Schemas:      []string{"urn:ietf:params:scim:api:messages:2.0:ListResponse"},
		TotalResults: len(res),
		StartIndex:   1,
		ItemsPerPage: len(res),
		Resources:    res,
	}
}

func (ss *SCIMServer) CreateUser(u SCIMUserResource) SCIMUserResource {
	ss.mu.Lock()
	defer ss.mu.Unlock()
	if u.ID == "" {
		u.ID = fmt.Sprintf("scim-%d", time.Now().UnixNano())
	}
	u.Schemas = []string{"urn:ietf:params:scim:schemas:core:2.0:User"}
	ss.users[u.ID] = u
	return u
}

