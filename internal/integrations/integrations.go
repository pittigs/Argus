type WebhookSubscription struct {
	ID        string    `json:"id"`
	URL       string    `json:"url"`
	Secret    string    `json:"secret"` // Shared HMAC secret
	Events    []string  `json:"events"` // "audit.critical", "jit.expired", "approval.needed"
	Format    string    `json:"format"` // "json", "slack", "teams"
	Active    bool      `json:"active"`
	CreatedAt time.Time `json:"created_at"`
}

type WebhookPayload struct {
	EventID   string    `json:"event_id"`
	EventType string    `json:"event_type"`
	Timestamp time.Time `json:"timestamp"`
	Data      any       `json:"data"`
}

type WebhookEngine struct {
	subscriptions map[string]WebhookSubscription
	mu            sync.RWMutex
}

func NewWebhookEngine() *WebhookEngine {
	we := &WebhookEngine{
		subscriptions: make(map[string]WebhookSubscription),
	}
	we.subscriptions["wh-sec-alert"] = WebhookSubscription{
		ID:        "wh-sec-alert",
		URL:       "https://hooks.slack.com/services/T00/B00/XXXXX",
		Secret:    "whsec_supersecuresecret123",
		Events:    []string{"audit.critical", "breakglass.triggered"},
		Format:    "slack",
		Active:    true,
		CreatedAt: time.Now().UTC(),
	}
	return we
}

func (we *WebhookEngine) ListSubscriptions() []WebhookSubscription {
	we.mu.RLock()
	defer we.mu.RUnlock()
	res := make([]WebhookSubscription, 0, len(we.subscriptions))
	for _, s := range we.subscriptions {
		clean := s
		clean.Secret = "••••••••••••"
		res = append(res, clean)
	}
	return res
}

func (we *WebhookEngine) SignPayload(payloadBytes []byte, secret string) string {
	mac := hmac.New(sha256.New, []byte(secret))
	mac.Write(payloadBytes)
	return hex.EncodeToString(mac.Sum(nil))
}

// ValidateWebhookTargetURL ensures protection against Server-Side Request Forgery (SSRF)
func ValidateWebhookTargetURL(rawURL string) error {
	u, err := url.Parse(rawURL)
	if err != nil {
		return fmt.Errorf("ungültige Webhook-URL: %w", err)
	}
	if u.Scheme != "http" && u.Scheme != "https" {
		return errors.New("nur HTTP und HTTPS Schemata sind zulässig")
	}

	host := u.Hostname()
	if host == "" {
		return errors.New("Hostname darf nicht leer sein")
	}

	// Block obvious loopback hostnames
	if strings.EqualFold(host, "localhost") || strings.EqualFold(host, "127.0.0.1") || strings.EqualFold(host, "::1") {
		return errors.New("SSRF Schutz: Loopback-Adressen sind als Webhook-Ziel nicht gestattet")
	}

	// Resolve and verify IP address
	ips, err := net.LookupIP(host)
	if err == nil {
		for _, ip := range ips {
			if ip.IsLoopback() || ip.IsPrivate() || ip.IsLinkLocalUnicast() || ip.IsLinkLocalMulticast() || ip.IsUnspecified() {
				return fmt.Errorf("SSRF Schutz: Ziel-IP %s ist eine interne oder private Netzwerkadresse und nicht erlaubt", ip.String())
			}
		}
	}
	return nil
}

func (we *WebhookEngine) RegisterSubscription(sub WebhookSubscription) error {
	if err := ValidateWebhookTargetURL(sub.URL); err != nil {
		return err
	}
	we.mu.Lock()
	defer we.mu.Unlock()
	we.subscriptions[sub.ID] = sub
	return nil
}

func (we *WebhookEngine) DispatchMock(subID string, payload WebhookPayload) (string, error) {
	we.mu.RLock()
	sub, ok := we.subscriptions[subID]
	we.mu.RUnlock()
	if !ok {
		return "", errors.New("webhook subscription not found")
	}

	if err := ValidateWebhookTargetURL(sub.URL); err != nil {
		return "", fmt.Errorf("webhook dispatch blocked: %w", err)
	}

	bytes, _ := json.Marshal(payload)
	sig := we.SignPayload(bytes, sub.Secret)
	return fmt.Sprintf("Dispatched to %s with Signature sha256=%s", sub.URL, sig), nil
}

